local harness = require('harness')
local testy = require('testy')

describe('Sel\'s idle set', function()
    it('is the one for the idle mode', function()
        local gs = harness.boot(testy.rdm())
        gs:console('gs c update')
        assert.same(testy.worn_by(testy.rdm_idle), gs:worn())
        gs:console('gs c cycle IdleMode')
        assert.equal('DT', gs.user.state.IdleMode.value)
        assert.same(testy.worn_by(testy.rdm_idle, {head = 'Malignance Chapeau', body = 'Malignance Tabard'}), gs:worn())
    end)

    it('is sets.idle[mode] for an idle mode set by name', function()
        local gs = harness.boot(testy.rdm())
        gs:console('gs c set IdleMode Refresh')
        assert.same(testy.worn_by(testy.rdm_idle, {head = 'Kaykaus Mitra +1'}), gs:worn())
    end)

    it('stays sets.idle in an idle mode the gear file has no set for', function()
        local gs = harness.boot(testy.rdm())
        gs:console('gs c set IdleMode Refresh')
        gs:console('gs c set IdleMode Regen')
        assert.equal('Regen', gs.user.state.IdleMode.value)
        assert.same(testy.worn_by(testy.rdm_idle), gs:worn())
    end)

    it('has sets.Kiting laid over it while Kiting is on', function()
        local gs = harness.boot(testy.rdm())
        gs:console('gs c toggle Kiting')
        assert.same(testy.worn_by(testy.rdm_idle, {body = 'Atrophy Tabard +3'}), gs:worn())
        gs:console('gs c toggle Kiting')
        assert.same(testy.worn_by(testy.rdm_idle), gs:worn())
    end)

    it('has sets.Kiting laid over the idle mode\'s set', function()
        local gs = harness.boot(testy.rdm())
        gs:console('gs c set IdleMode DT')
        gs:console('gs c toggle Kiting')
        assert.same(testy.worn_by(testy.rdm_idle, {head = 'Malignance Chapeau', body = 'Atrophy Tabard +3'}), gs:worn())
    end)
end)
