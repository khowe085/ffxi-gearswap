describe('gs equip', function()
    local function equip(gs, text)
        gs:console('gs equip ' .. text)
        return gs:traffic()
    end

    local function boot_sets()
        return boot('Testy_Sets.lua')
    end

    it('finds a set by its path, with or without sets in front', function()
        local gs = boot_sets()
        assert.same({{equip = {head = "Bunzi's Hat"}}}, equip(gs, 'sets.nested.deeper.deepest'))
        gs:console('gs equip sets.idle')
        gs:traffic()
        assert.same({{equip = {head = "Bunzi's Hat"}}}, equip(gs, 'nested.deeper.deepest'))
    end)

    it('is also gs e', function()
        local gs = boot_sets()
        gs:console('gs e sets.nested.deeper.deepest')
        assert.equal("Bunzi's Hat", gs:worn().head)
    end)

    it('finds a set by a key in brackets and quotes, which can hold spaces', function()
        local gs = boot_sets()
        assert.same({{equip = {head = 'Kaykaus Mitra +1'}}}, equip(gs, 'sets["mid cast"]'))
        assert.same({{equip = {main = "Bunzi's Rod"}}}, equip(gs, "sets['Cure III']"))
    end)

    it('finds a set by a key in brackets with a dot in it', function()
        local gs = boot_sets()
        assert.same({{equip = {right_ring = 'Kishar Ring'}}}, equip(gs, "sets.dotted['Dia II.Acc']"))
    end)

    it('finds a set by a number in brackets', function()
        local gs = boot_sets()
        assert.same({{equip = {head = 'Kaykaus Mitra +1'}}}, equip(gs, 'sets.numbered[2]'))
    end)

    it('finds a set by true or false in brackets', function()
        local gs = boot_sets()
        assert.same({{equip = {head = "Bunzi's Hat"}}}, equip(gs, 'sets.flagged[true]'))
        assert.same({{equip = {head = 'Kaykaus Mitra +1'}}}, equip(gs, 'sets.flagged[false]'))
    end)

    it('says so when there is no such set, and changes nothing', function()
        local gs = boot_sets()
        local worn = gs:worn()
        assert.same({}, equip(gs, 'sets.nothing.here'))
        assert.same({'GearSwap: Equip command cannot be completed. That set does not exist.'}, gs:chat())
        assert.same(worn, gs:worn())
    end)

    pending('says so when the path goes through something that is not a set: a path through a piece\'s name '
        .. '(sets.idle.head.deeper) indexes the name as a table, and the strings library raises an error')

    it('is left alone while the user file is off', function()
        local gs = boot_sets()
        gs:console('gs disable')
        assert.same({}, equip(gs, 'sets.nested.deeper.deepest'))
        assert.same({}, gs:chat_lines())
        assert.equal('Nyame Helm', gs:worn().head)
    end)

    it('raises an error when what it finds is not a set', function()
        local gs = boot_sets()
        assert.error_matches(function() gs:console('gs equip sets.not_a_set') end, 'Trying to combine non%-gear sets')
    end)
end)

describe('the events GearSwap takes from the game', function()
    it('unload tells the user file it is unloaded', function()
        local gs = boot()
        gs.game:fire('unload')
        assert.same({{event = 'file_unload', args = {}}}, plain.events(gs))
    end)

    it('login loads the user file again two seconds later', function()
        local gs = boot()
        local old = gs.env.user_env
        gs.game:fire('login', 'Testy')
        gs:advance(1.9)
        assert.equal(old, gs.env.user_env)
        gs:advance(0.2)
        assert.not_equal(old, gs.env.user_env)
        assert.equal('Testy_WHM.lua', gs.env.current_file)
    end)

    it('load loads the user file when the player is logged in', function()
        local gs = boot()
        gs.game:fire('load')
        gs:advance(0)
        assert.equal('Testy_WHM.lua', gs.env.current_file)
    end)

    it('a status change tells the user file the new status and the old, by name', function()
        local gs = boot()
        gs.game:set_status(33)
        gs.game:settle()
        assert.same({{event = 'status_change', new = 'Resting', old = 'Idle'}}, plain.events(gs))
    end)

    it('a change to or from dead, engaged dead or an event is left out', function()
        local gs = boot()
        for _, status in ipairs({2, 0, 3, 0, 4, 0}) do
            gs.game:set_status(status)
        end
        gs.game:settle()
        assert.same({}, plain.events(gs))
    end)
end)

