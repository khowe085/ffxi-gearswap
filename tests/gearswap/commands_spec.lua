local harness = require('harness')
local plain = require('plain')

local function boot(file)
    local gs = plain.boot(file or 'Testy_Events.lua')
    plain.events(gs)
    return gs
end

local function boot_corey_without_a_file()
    local gs = harness.boot({
        character = 'Corey', main_job = 'WHM', sub_job = 'RDM', expect_file = 'Corey_WHM.lua',
        items = {{name = 'Nyame Helm'}, {name = 'Nyame Mail'}},
    })
    gs:change_main_job('MON')
    assert.is_nil(gs.env.user_env, 'Corey has a file for the monipulator')
    gs:printed()
    gs:chat_lines()
    return gs
end

describe('gs load', function()
    it('loads the file it names, with .lua added to a name that lacks it', function()
        local gs = boot()
        gs:console('gs load Testy_Sets')
        assert.equal('Testy_Sets.lua', gs.env.current_file)
        assert.same({'GearSwap: Loaded your Testy_Sets.lua file!'}, gs:printed())
    end)

    it('takes a name with .lua as it is, in any case', function()
        local gs = boot()
        gs:console('gs LOAD testy_sets.LUA')
        assert.is_not_nil(gs.env.sets.nested)
    end)

    it('is also gs l', function()
        local gs = boot()
        gs:console('gs l Testy_Sets')
        assert.equal('Testy_Sets.lua', gs.env.current_file)
    end)

    it('gives the sets of the new file, and takes away those of the old', function()
        local gs = plain.boot()
        gs:console('gs load Testy_Sets')
        assert.is_not_nil(gs.env.sets.nested)
        assert.is_nil(gs.env.sets.precast)
    end)

    it('tells the old file it is unloaded, with its name', function()
        local gs = boot()
        local old = gs.user
        gs:console('gs load Testy_Sets')
        assert.same({{event = 'file_unload', args = {'Testy_Events.lua'}}}, old.events)
    end)

    it('says so when the file is not there', function()
        local gs = boot()
        gs:console('gs load Nothing_Here')
        assert.same({'GearSwap: File not found.'}, gs:chat())
        assert.equal('Testy_Events.lua', gs.env.current_file)
    end)

    it('says so when it is given no name', function()
        local gs = boot()
        gs:console('gs load')
        assert.same({'GearSwap: No file name was provided.'}, gs:chat())
    end)

    it('enables the user file if it was disabled', function()
        local gs = boot()
        gs:console('gs disable')
        gs:console('gs load Testy_Sets')
        assert.is_false(gs.env.gearswap_disabled)
    end)

    it('keeps a slot disabled that was disabled', function()
        local gs = boot()
        gs:console('gs disable head')
        gs:console('gs load Testy_Sets')
        assert.is_true(gs.env.disable_table[4])
    end)

    it('of a file Lua can\'t read says what is wrong and loads no file', function()
        local gs = boot()
        gs:console('gs load Testy_Broken')
        assert.matches('User file problem: ', gs:printed()[1])
        assert.is_nil(gs.env.current_file)
        assert.is_nil(gs.env.sets)
    end)

    it('of a file that raises an error says it failed to load', function()
        local gs = boot()
        assert.error_matches(function() gs:console('gs load Testy_Throws') end, 'GearSwap: File failed to load')
    end)

    it('makes the player\'s sets come from the new file for gs equip', function()
        local gs = boot()
        gs:console('gs load Testy_Sets')
        gs:console('gs equip sets.nested.deeper.deepest')
        assert.equal("Bunzi's Hat", gs:worn().head)
    end)
end)

describe('gs reload', function()
    it('loads the file the job\'s name gives, not the one gs load put in', function()
        local gs = boot()
        gs:console('gs load Testy_Sets')
        gs:console('gs reload')
        assert.equal('Testy_WHM.lua', gs.env.current_file)
    end)

    it('is also gs r', function()
        local gs = boot()
        gs:console('gs r')
        assert.equal('Testy_WHM.lua', gs.env.current_file)
    end)

    it('makes the file\'s globals new', function()
        local gs = boot('Testy_WHM.lua')
        gs.user.calls[1] = 'left over'
        gs:console('gs reload')
        assert.same({}, gs.env.user_env.calls)
    end)

    it('tells the old file it is unloaded', function()
        local gs = boot('Testy_Events.lua')
        local old = gs.user
        gs:console('gs reload')
        assert.same({{event = 'file_unload', args = {'Testy_Events.lua'}}}, old.events)
    end)
end)

describe('gs disable and gs enable', function()
    it('with no slot turn the user file off and on, and say so', function()
        local gs = boot()
        gs:console('gs disable')
        assert.same({'GearSwap: User file disabled'}, gs:printed())
        assert.is_true(gs.env.gearswap_disabled)
        gs:console('gs enable')
        assert.same({'GearSwap: User file enabled'}, gs:printed())
        assert.is_false(gs.env.gearswap_disabled)
    end)

    it('say nothing when the file is already as asked', function()
        local gs = boot()
        gs:console('gs enable')
        assert.same({}, gs:printed())
        gs:console('gs disable')
        gs:printed()
        gs:console('gs disable')
        assert.same({}, gs:printed())
    end)

    it('leave a spell to the game while the user file is off', function()
        local gs = boot('Testy_WHM.lua')
        gs:console('gs disable')
        assert.equal('/ma "Cure III" <me>', gs:type('/ma "Cure III" <me>'))
        assert.same({}, gs:traffic())
        assert.same({}, gs.user.calls)
    end)

    it('leave a status change alone while the user file is off', function()
        local gs = boot()
        gs:console('gs disable')
        gs:engage()
        assert.same({}, plain.events(gs))
    end)

    it('with all turn every slot off and on', function()
        local gs = boot()
        gs:console('gs disable all')
        assert.same({'GearSwap: All slots disabled.'}, gs:printed())
        for slot = 0, 15 do
            assert.is_true(gs.env.disable_table[slot], 'slot ' .. slot)
        end
        gs:console('gs enable all')
        assert.same({'GearSwap: All slots enabled.'}, gs:printed())
        for slot = 0, 15 do
            assert.is_false(gs.env.disable_table[slot], 'slot ' .. slot)
        end
    end)

    it('with slots turn those slots off and on, and name them', function()
        local gs = boot()
        gs:console('gs disable head body')
        assert.same({'GearSwap: [head, body] slots disabled.'}, gs:printed())
        assert.same({true, true, false}, {gs.env.disable_table[4], gs.env.disable_table[5], gs.env.disable_table[6]})
        gs:console('gs enable head body')
        assert.same({'GearSwap: [head, body] slots enabled.'}, gs:printed())
        assert.same({false, false}, {gs.env.disable_table[4], gs.env.disable_table[5]})
    end)

    it('with one slot say slot, not slots', function()
        local gs = boot()
        gs:console('gs disable head')
        assert.same({'GearSwap: [head] slot disabled.'}, gs:printed())
    end)

    it('with a name that is no slot say so', function()
        local gs = boot()
        gs:console('gs disable foo bar')
        assert.same({'GearSwap: Unable to find slots [foo, bar].'}, gs:printed())
        gs:console('gs disable foo')
        assert.same({'GearSwap: Unable to find slot [foo].'}, gs:printed())
    end)

    it('with slots and names that are none do the slots and say so of the others', function()
        local gs = boot()
        gs:console('gs disable head foo')
        assert.same({'GearSwap: [head] slot disabled.', 'GearSwap: Unable to find slot [foo].'}, gs:printed())
        assert.is_true(gs.env.disable_table[4])
    end)

    it('take any of the names a slot has, in any case, with what is no letter, digit or underscore left out', function()
        local gs = boot()
        gs:console('gs disable Ear1 L-Ring Right_Ring')
        assert.same({true, true, true}, {gs.env.disable_table[11], gs.env.disable_table[13], gs.env.disable_table[14]})
        assert.same({false, false}, {gs.env.disable_table[12], gs.env.disable_table[0]})
    end)

    it('with slots keep the user file on', function()
        local gs = boot()
        gs:console('gs disable head')
        assert.is_false(gs.env.gearswap_disabled)
    end)

    it('enable of slots puts on what a disabled slot held back, and nothing of a slot that held none', function()
        local gs = boot('Testy_WHM.lua')
        gs:console('gs disable head')
        gs:type('/ma "Cure III" <me>')
        gs:traffic()
        gs:console('gs enable head neck')
        assert.same({{equip = {head = 'Kaykaus Mitra +1'}}}, gs:traffic())
    end)
end)

describe('gs debugmode, gs demomode and gs showswaps', function()
    it('toggle debug mode, and say what it is', function()
        local gs = boot()
        gs:console('gs debugmode')
        assert.same({'GearSwap: Debug Mode set to true.'}, gs:printed())
        assert.is_true(gs.env._settings.debug_mode)
        gs:console('gs debugmode')
        assert.same({'GearSwap: Debug Mode set to false.'}, gs:printed())
        assert.is_false(gs.env._settings.debug_mode)
    end)

    it('take the name however it is written: with capitals, a dash or an underscore', function()
        local gs = boot()
        gs:console('gs DebugMode')
        gs:console('gs debug_mode')
        gs:console('gs debug-mode')
        assert.same({'GearSwap: Debug Mode set to true.', 'GearSwap: Debug Mode set to false.',
            'GearSwap: Debug Mode set to true.'}, gs:printed())
    end)

    it('toggle showing the swaps, and say what it is', function()
        local gs = boot()
        gs:console('gs showswaps')
        assert.same({'GearSwap: Show Swaps set to true.'}, gs:printed())
        assert.is_true(gs.env._settings.show_swaps)
        gs:console('gs show_swaps')
        assert.is_false(gs.env._settings.show_swaps)
    end)

    it('show the swaps GearSwap makes in the chat, under the event that made them', function()
        local gs = boot('Testy_WHM.lua')
        gs:console('gs showswaps')
        gs:chat_lines()
        gs:type('/ma "Cure III" <me>')
        local lines = gs:chat()
        assert.same({'------------------------- precast -------------------------', "head Bunzi's Hat", 'left_ring Kishar Ring'},
            {lines[1], lines[2], lines[3]})
    end)

    it('toggle demo mode, and say what it is', function()
        local gs = boot()
        gs:console('gs demomode')
        assert.same({'GearSwap: Demo Mode set to true.'}, gs:printed())
        assert.is_true(gs.env._settings.demo_mode)
        gs:console('gs demomode')
        assert.is_false(gs.env._settings.demo_mode)
    end)

    it('in demo mode show the swaps and send no equipment', function()
        local gs = boot('Testy_WHM.lua')
        gs:console('gs demomode')
        gs:chat_lines()
        gs:type('/ma "Cure III" <me>')
        local text = table.concat(gs:chat(), '\n')
        for _, expected in ipairs({'------------------pretarget -- Empty Table -----------------',
            '------------------------- precast -------------------------', "head Bunzi's Hat", 'left_ring Kishar Ring',
            '------------------------- midcast -------------------------', 'head Kaykaus Mitra +1',
            '------------------aftercast -- Empty Table -----------------'}) do
            assert.is_truthy(text:find(expected, 1, true), expected)
        end
        assert.same({}, gs:traffic())
        assert.equal('Nyame Helm', gs:worn().head)
    end)

    it('in demo mode the action is not sent, and is over at once for the hooks', function()
        local gs = boot('Testy_WHM.lua')
        gs:console('gs demomode')
        gs:type('/ma "Cure III" <me>')
        assert.same({'pretarget', 'precast', 'midcast', 'aftercast'}, plain.names(plain.calls(gs)))
        assert.same({}, gs.game.actions)
    end)

    it('debug mode lets gs eval run what it is given', function()
        local gs = boot()
        gs:console('gs debugmode')
        gs:console('gs eval tested_by_eval = 5')
        assert.equal(5, gs.env.tested_by_eval)
    end)

    it('without debug mode gs eval is a command GearSwap doesn\'t know', function()
        local gs = boot()
        gs:console('gs eval tested_by_eval = 5')
        assert.is_nil(gs.env.tested_by_eval)
        assert.same({'GearSwap: Command not found'}, gs:printed())
    end)
end)

