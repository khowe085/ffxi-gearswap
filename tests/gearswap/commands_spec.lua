describe('gs naked', function()
    local naked = {main = 'empty', sub = 'empty', ammo = 'empty', head = 'empty', body = 'empty', hands = 'empty', legs = 'empty',
        feet = 'empty', neck = 'empty', waist = 'empty', left_ear = 'empty', right_ear = 'empty', left_ring = 'empty',
        right_ring = 'empty', back = 'empty'}

    it('takes everything off, turns the user file off and says so', function()
        local gs = boot('Testy_WHM.lua')
        gs:console('gs naked')
        assert.same({{equip = naked}}, gs:traffic())
        assert.same({}, gs:worn())
        assert.is_true(gs.env.gearswap_disabled)
        assert.same({'GearSwap: Naked on, user file disabled until the next gs naked.'}, gs:chat())
    end)

    it('is also gs n', function()
        local gs = boot('Testy_WHM.lua')
        gs:console('gs n')
        assert.same({}, gs:worn())
    end)

    it('leaves a spell to the game while it is on', function()
        local gs = boot('Testy_WHM.lua')
        gs:console('gs naked')
        gs:traffic()
        assert.equal('/ma "Cure III" <me>', gs:type('/ma "Cure III" <me>'))
        assert.same({}, gs:traffic())
    end)

    it('turns the user file back on the next time, and puts nothing on', function()
        local gs = boot('Testy_WHM.lua')
        gs:console('gs naked')
        gs:chat_lines()
        gs:traffic()
        gs:console('gs naked')
        assert.same({'GearSwap: Naked off, user file enabled.'}, gs:chat())
        assert.is_false(gs.env.gearswap_disabled)
        assert.same({}, gs:traffic())
        assert.same({}, gs:worn())
    end)

    it('leaves the user file off the next time when it was off before', function()
        local gs = boot('Testy_WHM.lua')
        gs:console('gs disable')
        gs:console('gs naked')
        gs:chat_lines()
        gs:console('gs naked')
        assert.same({'GearSwap: Naked off, user file still disabled.'}, gs:chat())
        assert.is_true(gs.env.gearswap_disabled)
    end)

    it('is over for a bare gs enable, which turns the user file on: the next gs naked takes everything off again', function()
        local gs = boot('Testy_WHM.lua')
        gs:console('gs naked')
        gs:console('gs enable')
        assert.is_false(gs.env.gearswap_disabled)
        gs:chat_lines()
        gs:console('gs naked')
        assert.same({'GearSwap: Naked on, user file disabled until the next gs naked.'}, gs:chat())
    end)

    it('is over for a user file load, which turns the user file on', function()
        local gs = boot('Testy_WHM.lua')
        gs:console('gs naked')
        gs:console('gs load Testy_Sets')
        assert.is_false(gs.env.gearswap_disabled)
        gs:chat_lines()
        gs:console('gs naked')
        assert.same({'GearSwap: Naked on, user file disabled until the next gs naked.'}, gs:chat())
    end)

    it('says so when the user file has no naked set', function()
        local gs = boot('Testy_WHM.lua')
        gs.user.sets.naked = nil
        gs:console('gs naked')
        assert.same({'GearSwap: Naked command cannot be completed. That set does not exist.'}, gs:chat())
        assert.same({}, gs:traffic())
        assert.is_false(gs.env.gearswap_disabled)
    end)

    it('says so when no file is loaded', function()
        local gs = boot_corey_without_a_file()
        gs:console('gs naked')
        assert.same({'GearSwap: There is nothing to equip because there is no file loaded.'}, gs:chat())
    end)
end)

