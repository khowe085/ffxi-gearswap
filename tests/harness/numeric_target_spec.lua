local harness = require('harness')
local testy = require('testy')

describe('the stand-in game', function()
    it('gives a spell typed with a monster\'s id for its target the arrow GearSwap measures it from', function()
        local gs = harness.boot(testy.whm())
        gs:type(('/ma "Slow" %d'):format(gs.game.monster.id))
        local traffic = gs:traffic()
        assert.same({action = 'Slow', target = 'Apex Toad'}, traffic[#traffic])
    end)
end)
