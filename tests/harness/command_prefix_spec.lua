local Game = require('game')
local harness = require('harness')

describe('the stand-in game\'s console', function()
    it('runs a command with any number of @ before it, as GearSwap\'s send_command, which adds one, sends Sel\'s @input', function()
        local game = Game.new({res = harness.resources()})
        game:run_command('@@input /echo hello')
        assert.same({'input /echo hello'}, game.commands)
        assert.same({'/echo hello'}, game.typed)
    end)
end)
