local bit = assert(loadfile('tests/support/bit.lua'))()

describe('the bit stand-in for LuaJIT\'s', function()
    describe('tobit', function()
        it('keeps a number that fits in 32 signed bits', function()
            assert.equal(0, bit.tobit(0))
            assert.equal(1234, bit.tobit(1234))
            assert.equal(0x7FFFFFFF, bit.tobit(0x7FFFFFFF))
            assert.equal(-0x80000000, bit.tobit(-0x80000000))
        end)

        it('reads a number from 2^31 up as a negative one', function()
            assert.equal(-0x80000000, bit.tobit(0x80000000))
            assert.equal(-1, bit.tobit(0xFFFFFFFF))
        end)

        it('wraps a number beyond 32 bits', function()
            assert.equal(0, bit.tobit(0xFFFFFFFF + 1))
            assert.equal(1234, bit.tobit(2 ^ 40 + 1234))
        end)
    end)

    describe('band', function()
        it('keeps the bits both numbers have', function()
            assert.equal(0x78, bit.band(0x12345678, 0xFF))
            assert.equal(0, bit.band(0xF0, 0x0F))
            assert.equal(2, bit.band(6, 3))
        end)

        it('gives a result with the top bit set as a negative number', function()
            assert.equal(-0x01000000, bit.band(0xFF000000, 0xFF000000))
            assert.equal(-1, bit.band(0xFFFFFFFF, 0xFFFFFFFF))
        end)

        it('takes any number of arguments', function()
            assert.equal(0x30, bit.band(0xFF, 0xF0, 0x3C))
            assert.equal(-1, bit.band(0xFFFFFFFF))
        end)

        it('takes a negative number as its 32-bit pattern', function()
            assert.equal(255, bit.band(-1, 0xFF))
            assert.equal(-256, bit.band(-1, -256))
        end)

        it('drops what lies beyond 32 bits', function()
            assert.equal(5, bit.band(2 ^ 32 + 5, 0xFF))
        end)
    end)

    describe('bor', function()
        it('keeps the bits either number has', function()
            assert.equal(7, bit.bor(1, 2, 4))
            assert.equal(0xFF, bit.bor(0xF0, 0x0F))
        end)

        it('gives a result with the top bit set as a negative number', function()
            assert.equal(-0x7FFFFFFF, bit.bor(0x80000000, 1))
            assert.equal(-1, bit.bor(-256, 255))
        end)
    end)

    describe('bxor', function()
        it('keeps the bits that exactly one number has', function()
            assert.equal(6, bit.bxor(5, 3))
            assert.equal(0, bit.bxor(0xDEADBEEF, 0xDEADBEEF))
        end)

        it('takes any number of arguments, an odd count of ones winning', function()
            assert.equal(5, bit.bxor(1, 3, 7))
        end)

        it('flips every bit against 0xFFFFFFFF', function()
            assert.equal(0x5A5A5A5A, bit.bxor(0xA5A5A5A5, 0xFFFFFFFF))
        end)
    end)

    describe('bnot', function()
        it('flips all 32 bits', function()
            assert.equal(-1, bit.bnot(0))
            assert.equal(0, bit.bnot(-1))
            assert.equal(0, bit.bnot(0xFFFFFFFF))
            assert.equal(-0x80000000, bit.bnot(0x7FFFFFFF))
            assert.equal(0x7FFFFFFF, bit.bnot(0x80000000))
        end)
    end)

    describe('lshift', function()
        it('moves the bits up', function()
            assert.equal(8, bit.lshift(1, 3))
            assert.equal(0x1234 * 256, bit.lshift(0x1234, 8))
        end)

        it('drops the bits that leave the top, and goes negative when one lands there', function()
            assert.equal(-0x80000000, bit.lshift(1, 31))
            assert.equal(-16, bit.lshift(0xFFFFFFFF, 4))
            assert.equal(0, bit.lshift(0x80000000, 1))
        end)

        it('takes the count modulo 32', function()
            assert.equal(1, bit.lshift(1, 32))
            assert.equal(2, bit.lshift(1, 33))
        end)
    end)

    describe('rshift', function()
        it('moves the bits down, filling the top with zeros', function()
            assert.equal(0x12, bit.rshift(0x1234, 8))
            assert.equal(0x7FFFFFFF, bit.rshift(-1, 1))
            assert.equal(1, bit.rshift(0x80000000, 31))
        end)

        it('takes the count modulo 32', function()
            assert.equal(-1, bit.rshift(-1, 0))
            assert.equal(-1, bit.rshift(-1, 32))
        end)
    end)

    describe('arshift', function()
        it('moves the bits down, filling the top with the sign', function()
            assert.equal(16, bit.arshift(256, 4))
            assert.equal(-16, bit.arshift(-256, 4))
            assert.equal(-1, bit.arshift(0x80000000, 31))
            assert.equal(-1, bit.arshift(-1, 1))
        end)

        it('takes the count modulo 32', function()
            assert.equal(-256, bit.arshift(-256, 32))
        end)
    end)

    describe('tohex', function()
        it('gives eight lowercase digits by default', function()
            assert.equal('000000ff', bit.tohex(255))
            assert.equal('ffffffff', bit.tohex(-1))
            assert.equal('80000000', bit.tohex(0x80000000))
        end)

        it('gives the last n digits for a positive n', function()
            assert.equal('ff', bit.tohex(255, 2))
            assert.equal('5678', bit.tohex(0x12345678, 4))
        end)

        it('gives uppercase digits for a negative n', function()
            assert.equal('000000FF', bit.tohex(255, -8))
            assert.equal('BEEF', bit.tohex(0xDEADBEEF, -4))
        end)

        it('gives no more than eight digits', function()
            assert.equal('00000001', bit.tohex(1, 12))
        end)
    end)
end)
