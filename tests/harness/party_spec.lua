local harness = require('harness')
local testy = require('testy')

describe('the stand-in game\'s party and info', function()
    it('has the character alone in its party until another player joins', function()
        local gs = harness.boot(testy.whm())
        local party = gs.game.windower.ffxi.get_party()
        assert.equal(1, party.party1_count)
        assert.is_nil(party.p1)
    end)

    it('has a player who joins in the party list and among the mobs, in the party', function()
        local gs = harness.boot(testy.whm())
        gs:add_party_member({name = 'Friend'})
        local party = gs.game.windower.ffxi.get_party()
        assert.equal(2, party.party1_count)
        assert.equal('Friend', party.p1.name)
        assert.equal(party.p1.mob.id, gs.game.windower.ffxi.get_mob_by_name('Friend').id)
        assert.is_true(gs.game.windower.ffxi.get_mob_by_name('Friend').in_party)
    end)

    it('is a target GearSwap finds by name, as a member of the party', function()
        local gs = harness.boot(testy.whm())
        gs:add_party_member({name = 'Friend'})
        gs:traffic()
        gs:type('/ma "Cure III" Friend')
        assert.same({action = 'Cure III', target = 'Friend'}, gs:traffic()[2])
    end)

    it('takes the merit levels the boot gives it', function()
        local gs = harness.boot(testy.whm({merits = {sic_recast = 3}}))
        assert.equal(3, gs.game.windower.ffxi.get_player().merits.sic_recast)
    end)

    it('has no merits unless the boot gives them', function()
        local gs = harness.boot(testy.whm())
        assert.same({}, gs.game.windower.ffxi.get_player().merits)
    end)

    it('has a target arrow in its info, which GearSwap reads for a weapon skill with Ge in its name', function()
        local gs = harness.boot(testy.whm())
        assert.same({x = 0, y = 0, z = 0}, gs.game.windower.ffxi.get_info().target_arrow)
        gs.game.player.vitals.tp = 1000
        gs:traffic()
        gs:type('/ws "Tachi: Gekko" <t>')
        local traffic = gs:traffic()
        assert.same({action = 'Tachi: Gekko', target = 'Apex Toad'}, traffic[#traffic])
    end)
end)
